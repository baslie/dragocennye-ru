// Генератор связного тела для остальных постов — из вступления + тематических блоков.
function genBody(varietyId: string, intro: string, points: { h: string; p: string }[], quote: string): PostBlock[] {
  const v = varietyById.get(varietyId);
  const blocks: PostBlock[] = [{ type: "paragraph", text: intro }];
  points.forEach((pt, i) => {
    blocks.push({ type: "heading", text: pt.h });
    blocks.push({ type: "paragraph", text: pt.p });
    if (i === 0) blocks.push({ type: "quote", text: quote });
    if (i === 1 && v) {
      blocks.push({ type: "image", url: `/images/posts/${v.slug}-detail.jpg`, caption: `${v.name} из коллекции Дмитрия под дневным светом` });
    }
  });
  return blocks;
}

